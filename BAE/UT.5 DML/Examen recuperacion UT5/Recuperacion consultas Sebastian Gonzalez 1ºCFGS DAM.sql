SELECT PE.NOMBRE, PA.PUNTOS
FROM PERSONAJES PE
INNER JOIN PARTICIPACIONES PA
ON PE.ID_PERSONAJE = PA.ID_PERSONAJE
WHERE PA.PUNTOS = (SELECT MAX(PUNTOS) FROM PARTICIPACIONES);


