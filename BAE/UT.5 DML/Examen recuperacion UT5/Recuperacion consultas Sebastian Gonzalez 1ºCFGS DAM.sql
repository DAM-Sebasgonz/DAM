SELECT J.NICK , COUNT(DISTINCT PA.MAPA) AS MAPAS_DISTINTOS
FROM JUGADORES J
INNER JOIN PERSONAJES PE 
ON J.ID_JUGADOR = PE.ID_JUGADOR
INNER JOIN PARTICIPACIONES PAR 
ON PE.ID_PERSONAJE = PAR.ID_PERSONAJE
INNER JOIN PARTIDAS PA 
ON PAR.ID_PARTIDA = PA.ID_PARTIDA
GROUP BY J.ID_JUGADOR, J.NICK
HAVING COUNT(DISTINCT PA.MAPA) >= 2;



