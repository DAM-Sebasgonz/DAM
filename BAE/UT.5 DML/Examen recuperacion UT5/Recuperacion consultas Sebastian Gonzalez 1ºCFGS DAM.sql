SELECT J.NICK, COUNT(PA.ID_PARTIDA) AS TOTAL_PARTICIPACIONES, SUM(PA.PUNTOS) AS SUMA_PUNTOS
FROM JUGADORES J
INNER JOIN PERSONAJES PER
ON J.ID_JUGADOR = PER.ID_JUGADOR
INNER JOIN PARTICIPACIONES PA 
ON PER.ID_PERSONAJE = PA.ID_PERSONAJE
GROUP BY J.ID_JUGADOR, J.NICK;

